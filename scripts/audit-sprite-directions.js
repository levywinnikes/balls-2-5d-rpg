/**
 * Audit east/west sprite folders vs hero_base; writes runtime meta for the engine.
 *
 * Usage:
 *   node scripts/audit-sprite-directions.js
 *   node scripts/audit-sprite-directions.js --fix
 *   node scripts/audit-sprite-directions.js --entity orc --fix
 */
const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");
const { PNG } = require("pngjs");

const GENERATED_ROOT = path.join(
  process.cwd(),
  "public",
  "assets",
  "sprites",
  "generated",
);
const META_PATH = path.join(
  process.cwd(),
  "src",
  "three-d",
  "runtime",
  "sprite-direction-meta.json",
);

const DEFAULT_ENTITIES = [
  "goblin_lanceiro",
  "skeleton",
  "orc",
  "rat",
  "bear",
  "dragon",
  "demon",
];

function loadRgba(filePath) {
  if (!fs.existsSync(filePath)) {
    return null;
  }
  return PNG.sync.read(fs.readFileSync(filePath));
}

function flipHorizontal(png) {
  const out = new PNG({ width: png.width, height: png.height });
  for (let y = 0; y < png.height; y += 1) {
    for (let x = 0; x < png.width; x += 1) {
      const si = (png.width * y + x) * 4;
      const dx = png.width - 1 - x;
      const di = (png.width * y + dx) * 4;
      out.data[di] = png.data[si];
      out.data[di + 1] = png.data[si + 1];
      out.data[di + 2] = png.data[si + 2];
      out.data[di + 3] = png.data[si + 3];
    }
  }
  return out;
}

function silhouetteDistance(a, b) {
  if (!a || !b) {
    return Number.POSITIVE_INFINITY;
  }
  const w = Math.min(a.width, b.width);
  const h = Math.min(a.height, b.height);
  let sum = 0;
  let n = 0;
  for (let y = 0; y < h; y += 1) {
    for (let x = 0; x < w; x += 1) {
      const ai = (a.width * y + x) * 4;
      const bi = (b.width * y + x) * 4;
      const aOn = a.data[ai + 3] > 20;
      const bOn = b.data[bi + 3] > 20;
      if (!aOn && !bOn) {
        continue;
      }
      n += 1;
      const dr = (aOn ? a.data[ai] : 0) - (bOn ? b.data[bi] : 0);
      const dg = (aOn ? a.data[ai + 1] : 0) - (bOn ? b.data[bi + 1] : 0);
      const db = (aOn ? a.data[ai + 2] : 0) - (bOn ? b.data[bi + 2] : 0);
      const da = Number(aOn) - Number(bOn);
      sum += Math.abs(dr) + Math.abs(dg) + Math.abs(db) + Math.abs(da) * 128;
    }
  }
  return n === 0 ? Number.POSITIVE_INFINITY : sum / n;
}

function auditEntity(entityId, heroEast, heroWest, heroEastFlipped) {
  const base = path.join(GENERATED_ROOT, entityId, "character_rotations");
  const east = loadRgba(path.join(base, "east.png"));
  const west = loadRgba(path.join(base, "west.png"));
  if (!east || !west) {
    return { entityId, status: "missing" };
  }

  const eastAsEast = silhouetteDistance(east, heroEast);
  const eastAsWest = silhouetteDistance(east, heroWest);
  const eastAsFlippedEast = silhouetteDistance(east, heroEastFlipped);
  const westAsWest = silhouetteDistance(west, heroWest);
  const westAsEast = silhouetteDistance(west, heroEast);

  const eastBestAlt = Math.min(eastAsWest, eastAsFlippedEast);
  const westBestAlt = westAsEast;
  const swapMargin = 0.92;
  const eastLooksSwapped =
    eastBestAlt < eastAsEast * swapMargin && eastBestAlt + 8 < eastAsEast;
  const westLooksSwapped =
    westBestAlt < westAsWest * swapMargin && westBestAlt + 8 < westAsWest;
  const swapped = eastLooksSwapped && westLooksSwapped;

  const selfMirrorEast = silhouetteDistance(east, flipHorizontal(east));
  const selfMirrorWest = silhouetteDistance(west, flipHorizontal(west));
  const eastWestDistinct =
    silhouetteDistance(east, west) >
    Math.min(selfMirrorEast, selfMirrorWest) * 0.4;

  let status = "ok";
  if (!eastWestDistinct) {
    status = "ambiguous";
  } else if (swapped) {
    status = "swap_needed";
  } else if (eastLooksSwapped || westLooksSwapped) {
    status = "mismatch";
  }

  return {
    entityId,
    status,
    eastAsEast,
    eastAsWest,
    swapped,
  };
}

function writeDirectionMeta(results) {
  const entities = {};
  results.forEach((row) => {
    if (row.status === "missing") {
      return;
    }
    entities[row.entityId] = {
      status: row.status,
      swapEastWestAssets: row.status === "swap_needed",
    };
  });

  const payload = {
    version: 1,
    generatedAt: new Date().toISOString(),
    note:
      "Auto-generated by npm run audit:sprite-directions. swapEastWestAssets=true applies runtime E/W remap.",
    entities,
  };

  fs.writeFileSync(`${META_PATH}`, `${JSON.stringify(payload, null, 2)}\n`);
  console.log(`[audit-direction] wrote ${META_PATH}`);
}

function parseArgs(argv) {
  const args = { fix: false, entities: [] };
  for (let i = 2; i < argv.length; i += 1) {
    if (argv[i] === "--fix") {
      args.fix = true;
    } else if (argv[i] === "--entity" && argv[i + 1]) {
      args.entities.push(argv[i + 1]);
      i += 1;
    }
  }
  return args;
}

function main() {
  const args = parseArgs(process.argv);
  const heroBase = path.join(GENERATED_ROOT, "hero_base", "character_rotations");
  const heroEast = loadRgba(path.join(heroBase, "east.png"));
  const heroWest = loadRgba(path.join(heroBase, "west.png"));
  if (!heroEast || !heroWest) {
    console.error("[audit-direction] hero_base rotations missing");
    process.exit(1);
  }
  const heroEastFlipped = flipHorizontal(heroEast);

  const entities =
    args.entities.length > 0
      ? args.entities
      : DEFAULT_ENTITIES.filter((id) =>
          fs.existsSync(path.join(GENERATED_ROOT, id)),
        );

  let failed = false;
  const results = [];

  entities.forEach((entityId) => {
    let row = auditEntity(entityId, heroEast, heroWest, heroEastFlipped);
    const tag =
      row.status === "ok"
        ? "OK"
        : row.status === "swap_needed"
          ? "SWAP"
          : row.status.toUpperCase();
    console.log(`[audit-direction] ${tag.padEnd(7)} ${row.entityId}`);

    if (row.status === "swap_needed" && args.fix) {
      execSync(`node scripts/swap-sprite-east-west.js --entity ${entityId}`, {
        stdio: "inherit",
      });
      row = auditEntity(entityId, heroEast, heroWest, heroEastFlipped);
      console.log(`[audit-direction] FIXED ${entityId} → ${row.status}`);
    } else if (row.status === "swap_needed") {
      console.log(
        `  → npm run audit:sprite-directions -- --entity ${entityId} --fix`,
      );
    }

    if (row.status !== "ok" && row.status !== "missing") {
      failed = true;
    }
    results.push(row);
  });

  writeDirectionMeta(results);

  if (failed) {
    process.exit(1);
  }
  console.log("[audit-direction] all entities OK");
}

main();
